# === Stage 54: Добавь режим избранных записей и быстрый доступ к ним ===
# Project: PromoPlanner
ЗАИЗБРАННЫЕ = {}
БЫСТРЫЕ = {}

def добавить_в_избранное_запись(запись):
    ЗАИЗБРАННЫЕ[id(запись)] = запись
    БЫСТРЫЕ[id(запись)] = БЫСТРЫЕ.get(id(запись), 0) + 1

def в_избранном():
    return list(ЗАИЗБРАННЫЕ.values())

def быстрый_доступ(ключ):
    return ЗАИЗБРАННЫЕ.get(ключ)

def добавить_быстрый_доступ(запись, имя):
    БЫСТРЫЕ[имя] = запись

def все_быстрые():
    return dict(БЫСТРЫЕ)

def удалить_из_избранного(ключ):
    ЗАИЗБРАННЫЕ.pop(ключ, None)
    БЫСТРЫЕ.pop(ключ, None)
